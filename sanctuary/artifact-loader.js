// Dynamic loader for all artifacts
export async function loadArtifact(path) {
  try {
    const module = await import(path);
    return module.default;
  } catch (error) {
    console.error(`Failed to load artifact: ${path}`, error);
    return null;
  }
}

// Load all artifacts of a given type
export async function loadArtifactsByType(type) {
  const artifacts = artifactRegistry[type] || [];
  const loaded = await Promise.all(
    artifacts.map(async (meta) => {
      const data = await loadArtifact(meta.path);
      return data ? { ...meta, data } : null;
    })
  );
  return loaded.filter(Boolean);
}

// Load all artifacts
export async function loadAllArtifacts() {
  const [scrolls, sigils, glyphs, resonanceFragments] = await Promise.all([
    loadArtifactsByType('scrolls'),
    loadArtifactsByType('sigils'),
    loadArtifactsByType('glyphs'),
    loadArtifactsByType('resonanceFragments')
  ]);
  
  // Load received content separately
  const received = {
    glyphs: artifactRegistry.received.glyphs,
    scrolls: artifactRegistry.received.scrolls,
    fragments: artifactRegistry.received.fragments,
    resonance: artifactRegistry.received.resonance
  };
  
  return {
    scrolls,
    sigils,
    glyphs,
    resonanceFragments,
    received,
    total: scrolls.length + sigils.length + glyphs.length + resonanceFragments.length
  };
}

