// Quick lookup: get full sigil data by name
export function getSigilData(sigilName) {
  const symbol = SIGIL_SYMBOL_MAP[sigilName];
  const lore = EXTENDED_SIGIL_LORE[sigilName];
  
  return {
    name: sigilName,
    symbol: symbol?.symbol || '✦',
    alt: symbol?.alt || '◈',
    unicode: symbol?.unicode || '',
    description: lore?.desc || '',
    tags: lore?.tags || [],
  };
}

// Get all sigils by tag
export function getSigilsByTag(tag) {
  return Object.keys(EXTENDED_SIGIL_LORE)
    .filter(sigil => EXTENDED_SIGIL_LORE[sigil].tags.includes(tag))
    .map(getSigilData);
}

// Random sigil selector (for ritual generation)
export function getRandomSigil(count = 1) {
  const allSigils = Object.keys(SIGIL_SYMBOL_MAP);
  const selected = [];
  
  for (let i = 0; i < count; i++) {
    const random = allSigils[Math.floor(Math.random() * allSigils.length)];
    selected.push(getSigilData(random));
  }
  
  return count === 1 ? selected[0] : selected;
}
